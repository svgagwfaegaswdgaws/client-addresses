PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS Country (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CountryFull TEXT NOT NULL COLLATE NOCASE UNIQUE CHECK(length(trim(CountryFull)) BETWEEN 1 AND 120),
  CountryShort TEXT NOT NULL COLLATE NOCASE UNIQUE CHECK(length(trim(CountryShort)) BETWEEN 1 AND 20)
);
CREATE TABLE IF NOT EXISTS Region (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CountryID INTEGER NOT NULL REFERENCES Country(ID) ON DELETE RESTRICT,
  Region TEXT NOT NULL COLLATE NOCASE CHECK(length(trim(Region)) BETWEEN 1 AND 120),
  UNIQUE(CountryID, Region)
);
CREATE TABLE IF NOT EXISTS City (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  RegionID INTEGER NOT NULL REFERENCES Region(ID) ON DELETE RESTRICT,
  City TEXT NOT NULL COLLATE NOCASE CHECK(length(trim(City)) BETWEEN 1 AND 120),
  UNIQUE(RegionID, City)
);
CREATE TABLE IF NOT EXISTS Address (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Person TEXT NOT NULL CHECK(length(trim(Person)) BETWEEN 1 AND 160),
  CityID INTEGER NOT NULL REFERENCES City(ID) ON DELETE RESTRICT,
  Street TEXT NOT NULL CHECK(length(trim(Street)) BETWEEN 1 AND 160),
  Building TEXT NOT NULL CHECK(length(trim(Building)) BETWEEN 1 AND 30),
  Office TEXT NOT NULL DEFAULT '' CHECK(length(Office) <= 30)
);
CREATE INDEX IF NOT EXISTS idx_region_country ON Region(CountryID);
CREATE INDEX IF NOT EXISTS idx_city_region ON City(RegionID);
CREATE INDEX IF NOT EXISTS idx_address_city ON Address(CityID);
